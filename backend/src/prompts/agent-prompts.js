/**
 * 根据 agentType 组装 system prompt
 * @param {string} agentType 当前 agent 类型
 * @param {string} toolsDesc 工具描述文本
 * @returns {string} 最终 system prompt
 */
export function buildSystemPrompt(agentType, toolsDesc) {
  const agentPrompt = (typeof AGENT_PROMPTS !== 'undefined') ? AGENT_PROMPTS[agentType] : null;
  const sharedHints = REMINDER_TOOL_HINT + '\n\n' + CONTEXT_TOOL_HINT;
  if (agentPrompt) {
    return agentPrompt + '\n\n' + sharedHints;
  }
  return defaultSystemPrompt(toolsDesc);
}

export default AGENT_PROMPTS;
